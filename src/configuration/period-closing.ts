/**
 * Шапка документа «Закрытие периода»: граница закрытого периода. Объявлена отдельно от документа,
 * потому что её читает политика закрытого периода, а политику подключают продажа, возврат
 * и рассрочка. Сам документ хранит начисление зарплаты, которое считается по этим документам:
 * импорт документа из политики замкнул бы файлы в кольцо.
 *
 * Это не файл объекта: объект регистрирует `documents/period-closing.document.ts`, дополняя
 * шапку. Запросы по шапке читают ту же таблицу документа.
 */
import { document } from '../server/metadata/index.js';

/** Дата документа означает оформление закрытия; `closedThrough` задаёт его учётную границу включительно. */
export const periodClosingHead = document('periodClosing')
    .title('Закрытие периода')
    .field('closedThrough', (field) => field.date().title('Закрыто по').required());
