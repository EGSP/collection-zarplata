/**
 * Регистр «Применённые купоны»: купоны, по которым проведённые продажи дали скидку. Продажа
 * записывает по движению на каждую строку товара с купоном: акцию, номер купона и количество 1.
 * Итог по акции показывает, сколько её купонов применено, итог по акции и номеру — применён ли
 * этот купон.
 *
 * Отмена проведения и отмена продажи снимают её движения, и номер освобождается. Возврат
 * купон не восстанавливает: движений в этот регистр он не пишет.
 *
 * Предел количества и уникальность номера проверяют политика продажи и действие «Применить купон»
 * (модуль `coupons.ts`): ограничение регистра задаёт только нижнюю границу итога, а предел
 * количества берётся из справочника.
 */
import { register, type ObjectTarget } from '../../server/metadata/index.js';
import { Coupons } from '../catalogs/coupons.catalog.js';

export const AppliedCoupons = register('appliedCoupons')
    .title('Применённые купоны')
    // Продажа записывает движения в этот регистр, а её товары ссылаются на справочник купонов.
    // Ссылка задана функцией с явным типом, чтобы файлы не зависели друг от друга при загрузке.
    .dimension('coupon', (field) => field.reference((): ObjectTarget => Coupons).title('Купон').required())
    .dimension('number', (field) => field.string().title('Номер купона').required().maximumLength(50))
    .resource('count', (field) => field.number().title('Количество').integer().required());
