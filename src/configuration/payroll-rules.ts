/**
 * Правила начисления зарплаты: ставка по каждому товару. Расчёт в `payroll.ts` определяет, какие
 * суммы, когда и кому начисляются; этот модуль решает только, сколько процентов от них получает
 * сотрудник. Правила будут дополняться порогами, сериями продаж и скидками на товары, поэтому
 * ставка получает описание начисляемой части, а не одно число.
 *
 * При изменении правил меняется и `title`: название сохраняется в документе «Начисление
 * зарплаты» и показывает, по каким правилам посчитан закрытый период. Закрытые начисления
 * правила не пересчитывают.
 */

/**
 * Часть продажи, которая начисляется отдельно: деньги начисляются продажей, рассрочки по продаже —
 * своими документами по своим условиям.
 */
export type PayrollPartKind = 'money' | 'bankInstallment' | 'ownInstallment';

/** Начисляемая часть товара: по ней правило выбирает ставку. */
export interface PayrollRateContext {
    readonly part: PayrollPartKind;
    /** Название товара. */
    readonly goods: string;
    /** Доля итога товара, приходящаяся на часть, в копейках. */
    readonly base: number;
}

/** Действующие правила. */
export const payrollRules = {
    /** Название версии правил: сохраняется в начислении. */
    title: 'Базовые 4 %',
    /**
     * Ставка в процентах для каждого сотрудника смены. Пока одна для всех частей; у банковской
     * рассрочки ставка будет своей.
     */
    rate: (_context: PayrollRateContext): number => 4,
};
