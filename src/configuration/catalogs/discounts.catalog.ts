/** Скидки: именованные проценты, которые продавец подставляет в строку товара. */
import { catalog } from '../../server/metadata/index.js';

/**
 * Справочник служит только источником подсказок: строка товара хранит число процента, а не ссылку
 * на скидку. Поэтому изменение или пометка удаления скидки не меняет уже записанные документы.
 * Полей на форме немного, поэтому новая запись создаётся в окне поверх списка.
 */
export const Discounts = catalog('discounts')
    .title('Скидки')
    .field('percentage', (field) => field.number().title('Процент').minimum(0).maximum(100).required())
    .form((form) => form.creation('dialog'));
