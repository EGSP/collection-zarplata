/**
 * Ставки по рассрочке: доля, которую забирает банк от суммы рассрочки. Рассрочка по продаже ссылается
 * на ставку, а расчёт зарплаты по ней уменьшает базу начисления и выбирает ступень ставки сотрудника.
 */
import { catalog } from '../../server/metadata/index.js';

/**
 * Наименование ставки собственной рассрочки: 0 %, магазин ничего не отдаёт банку. Запись создаётся
 * при запуске сервера, если её нет, и проставляется собственной рассрочке.
 */
export const ownInstallmentRateName = 'Собственная';

/**
 * Полей немного, поэтому новая запись создаётся в окне поверх списка. Представление показывает
 * процент рядом с названием: при выборе ставки в рассрочке размер доли банка виден сразу.
 */
export const InstallmentRates = catalog('installmentRates')
    .title('Ставки по рассрочке')
    .field('percentage', (field) => field.number().title('Процент').minimum(0).maximum(100).required())
    .presentation([{ field: 'name' }, { text: ' ' }, { field: 'percentage', format: 'number' }, { text: ' %' }])
    .form((form) => form.creation('dialog'));
