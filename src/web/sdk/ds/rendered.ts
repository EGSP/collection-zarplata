/**
 * Есть ли у элемента раскладка: он сам и все его предки показаны, то есть ни на ком нет
 * `display: none`.
 *
 * Функция защищает замеры размеров от скрытых вкладок. Неактивная вкладка окна или панели
 * скрывается через `display: none`, и её элементы теряют размеры: ширина и высота становятся
 * нулевыми, а `getComputedStyle` отдаёт заданные в CSS шаблоны вместо пикселей, например
 * `repeat(4, minmax(0px, 1fr))` у колонок сетки. `ResizeObserver` при скрытии вызывает замер, и
 * компонент запомнил бы эти значения: лента сжалась бы до наименьшей высоты, страница перешла бы
 * на узкую точку перелома. Пока вкладка скрыта, это не видно, но при возвращении на неё неверная
 * раскладка держится до следующего события.
 *
 * Поэтому замер, который вызывается из `ResizeObserver` или события окна, сначала спрашивает
 * `isRendered` и у скрытого элемента ничего не меняет. При показе вкладки размеры наблюдаемых
 * элементов снова меняются, и `ResizeObserver` вызывает замер уже с настоящими значениями:
 *
 * ```ts
 * const update = () => {
 *     if (isRendered(area)) setHeight(measure(area));
 * };
 * new ResizeObserver(update).observe(area);
 * ```
 */
export function isRendered(element: Element): boolean {
    // У элемента без раскладки нет ни одного прямоугольника, даже нулевого размера.
    return element.getClientRects().length > 0;
}
